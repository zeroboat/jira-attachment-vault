const DICTS = { en, ko };
export type Lang = keyof typeof DICTS;
export const LANGS: Record<Lang, string> = { en: "English", ko: "한국어" };

function readLang(): Lang {
  try {
    const v = localStorage.getItem("lang");
    if (v && v in DICTS) return v as Lang;
  } catch {
    /* storage blocked */
  }
  return "en";
}

export const lang: Lang = readLang();
document.documentElement.lang = lang;
const dict: Record<Key, string> = DICTS[lang];
document.title = dict["app.fullName"];

export function setLang(next: Lang) {
  try {
    localStorage.setItem("lang", next);
  } catch {
    /* storage blocked */
  }
  location.reload();
}

/** t("key", { n: 3 }). "a|b" picks a when n === 1, else b (English plurals). */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  let s = dict[key] ?? key;
  if (s.includes("|")) s = s.split("|")[Number(params.n) === 1 ? 0 : 1];
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

/** Labels for enum-like values coming from the API; falls back to the raw value. */
export function label(prefix: "state" | "jobStatus" | "jobKind" | "action", value: string): string {
  const k = `${prefix}.${value}` as Key;
  return k in dict ? dict[k] : value;
}

/** Cleanup skip reasons are codes ("embedded", "error:KeyError"); older rows may hold free text. */
export function reasonLabel(code: string): string {
  if (code.startsWith("error:")) return t("reason.error", { name: code.slice(6) });
  const k = `reason.${code}` as Key;
  return k in dict ? dict[k] : code;
}
